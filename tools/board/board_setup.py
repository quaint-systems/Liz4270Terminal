def _class(name, clearance, track, via, drill, pair, gap, priority):
    return {'name': name, 'clearance': clearance, 'track_width': track, 'via_diameter': via, 'via_drill': drill,
            'diff_pair_width': pair, 'diff_pair_gap': gap, 'diff_pair_via_gap': gap, 'priority': priority,
            'microvia_diameter': 0.3, 'microvia_drill': 0.1, 'bus_width': 12, 'wire_width': 6, 'line_style': 0,
            'pcb_color': 'rgba(0, 0, 0, 0.000)', 'schematic_color': 'rgba(0, 0, 0, 0.000)'}


def project():
    """The project file's board settings, as build_board.py writes it before KiCad loads the board."""
    classes = [_class(*DEFAULT, priority=2147483647)]
    patterns = []
    for (i, (name, clearance, track, via, drill, pair, gap, nets)) in enumerate(CLASSES):
        classes.append(_class(name, clearance, track, via, drill, pair, gap, priority=i))
        patterns += [{'netclass': name, 'pattern': p} for p in nets]
    return {'board': {'design_settings': {'rules': dict(RULES)}},
            'meta': {'filename': 'liz4270.kicad_pro', 'version': 3},
            'net_settings': {'classes': classes, 'meta': {'version': 4}, 'netclass_patterns': patterns}}


def project_text():
    return json.dumps(project(), indent=2, sort_keys=True) + '\n'
