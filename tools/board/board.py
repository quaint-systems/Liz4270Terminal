"""The Liz4270 board, revision A, one sheet per block (#90)."""

import paths
import sheet_audio
import sheet_coax
import sheet_mcu
import sheet_power
import sheet_usb_host
import sheet_video
from schematic import Project

SHEETS = [sheet_mcu, sheet_coax, sheet_video, sheet_usb_host, sheet_audio, sheet_power]


def project(directory=paths.BOARD):
    p = Project('liz4270', directory, title='Liz4270 rev A', rev='A', date='2026-10-08', company='CoffeeMuse',
                comments=['CERN-OHL-P-2.0',
                          'Generated by tools/board/build_schematic.py: change the generator, not this file'])
    p.note('Liz4270 rev A: a 3270 CUT terminal on an RP2350B, impersonating an IBM 3483-V.')
    p.note('Coax front end: interface3 port 0 (Hans Hübner, ISC), as on the Liz 4174.')
    p.note('Core regulator and crystal: Raspberry Pi, Hardware design with RP2350, and its minimal design (MIT).')
    for module in SHEETS:
        module.build(p)
    return p
